const byName = (n) => (TABLE[n] ? { name: n, protocol: TABLE[n][0], dataVersion: TABLE[n][1] } : null);

function byProtocol(p) {
  // höchste (neueste) Version mit diesem Protokoll
  const hit = Object.keys(TABLE).find((n) => TABLE[n][0] === p);
  return hit ? byName(hit) : null;
}

// Extrahiert z.B. "1.21.4" aus "Paper 1.21.4", "Spigot 1.20.1-R0.1" ...
function parseServerVersion(versionName, protocol) {
  const m = /(\d+\.\d+(?:\.\d+)?)/.exec(versionName || '');
  if (m) {
    const exact = byName(m[1]);
    if (exact) return exact;
  }
  return byProtocol(protocol);
}

